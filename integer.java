public class integer {
    public static void main(String args[]){
        // integer //
        byte a = 55;
        short b = 5;
        int c = 45;
        long d = 78;
        System.out.println("the value of integers -->"+ a +"," + b + "," + c + ","+ d);
        // real numbers //
        float num1 = 78.97f;
        double num2 = 67.45;
        System.out.println("the real numbers are "+ num1 +","+ num2);
        // char data type//
        char x = 'h';
        System.out.println("the character is "+ x);
        // boolean data type //
        boolean bool = true;
        System.out.println("the boolean value is "+ bool);
    }

}